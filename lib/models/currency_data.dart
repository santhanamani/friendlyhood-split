class CurrencyOption {
  const CurrencyOption(this.code, this.name, this.symbol, this.flag);

  final String code;
  final String name;
  final String symbol;
  final String flag;

  bool matches(String query) {
    final value = query.trim().toLowerCase();
    return value.isEmpty ||
        code.toLowerCase().contains(value) ||
        name.toLowerCase().contains(value) ||
        symbol.toLowerCase().contains(value);
  }
}


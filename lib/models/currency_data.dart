CurrencyOption currencyForCode(String code) => worldCurrencies.firstWhere(
      (item) => item.code == code.toUpperCase(),
      orElse: () => const CurrencyOption('INR', 'Indian Rupee', '₹', '🇮🇳'),
    );

String formatMoney(double value, String currencyCode) {
  final currency = currencyForCode(currencyCode);
  return NumberFormat.currency(
    locale: 'en',
    name: currency.code,
    symbol: currency.symbol,
    decimalDigits: 0,
  ).format(value);
}

